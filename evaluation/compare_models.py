#!/usr/bin/env python3
"""Compare the offline evidence template with a real LLM on the SAME labelled set.

    # with OPENROUTER_API_KEY / LLM_PROVIDER=openrouter in .env (OPENROUTER_MODEL=auto picks the best for the key)
    python evaluation/compare_models.py                       # 30 users, template vs LLM
    python evaluation/compare_models.py --users 60 --sleep 4  # free models: ~15 requests/minute
    python evaluation/compare_models.py --hybrid              # add a third run: LLM verdicts + LLM extraction

Writes evaluation/results/model_comparison.md. The groundedness rows measure how often the real
model cited evidence that does not exist, and how many the self-check repaired or flagged.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from evaluation import run_benchmark as rb  # noqa: E402


def _args(base, **kw):
    a = argparse.Namespace(mode=base.mode, users=base.users, insiders=base.insiders, rows_per_user=base.rows_per_user,
                           seed=base.seed, llm=False, extractor="rules", tag="", sleep=0.0,
                           hallucination_rate=0.0, retry_failure_rate=0.0)
    for k, v in kw.items():
        setattr(a, k, v)
    return a


def row(name: str, r: dict) -> str:
    d, g = r["detection"], r["groundedness_live"]
    total = sum(g.values()) or 1
    model = ", ".join(r["models"])
    return (f"| {name} | `{model}` | {d['precision']:.3f} | {d['recall']:.3f} | {d['f1']:.3f} | {d['fpr']:.3f} | "
            f"{r['retrieval_accuracy']['f1']:.3f} | {r['threat_correlation']['precision']:.3f} | "
            f"{g.get('grounded', 0)}/{total} | {g.get('regenerated', 0)} | {g.get('unverified', 0)} | "
            f"{1000 * r['response_time']['query_total']['mean_s']:.0f} ms |")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--mode", default="auto", choices=["auto", "real", "injected"])
    ap.add_argument("--users", type=int, default=30)
    ap.add_argument("--insiders", type=int, default=6)
    ap.add_argument("--rows-per-user", type=int, default=60)
    ap.add_argument("--seed", type=int, default=42)
    ap.add_argument("--sleep", type=float, default=0.0)
    ap.add_argument("--hybrid", action="store_true")
    a = ap.parse_args()
    runs = [("Evidence template (no LLM)", rb.run(_args(a, tag="cmp_template")))]
    runs.append(("LLM verdicts", rb.run(_args(a, llm=True, tag="cmp_llm", sleep=a.sleep))))
    if a.hybrid:
        runs.append(("LLM verdicts + LLM extraction", rb.run(_args(a, llm=True, extractor="hybrid", tag="cmp_hybrid", sleep=a.sleep))))
    if all("template" in m for _, r in runs[1:] for m in r["models"]):
        print("\n!! The LLM runs fell back to the template — no model answered. Check the key/model with "
              "`curl localhost:8000/llm/test` or the dashboard's Send test prompt, then re-run.")
    r0 = runs[0][1]
    lines = ["# Model comparison", "",
             f"Same labelled set for every row: {r0['dataset']['users']} users ({r0['dataset']['insiders']} insiders), "
             f"ground truth `{r0['label_mode']}`, seed {a.seed}. Generated by `evaluation/compare_models.py`.", "",
             "| Run | Model | Precision | Recall | F1 | FPR | Evidence F1 | Correlation precision | Grounded first try | Repaired by retry | Flagged unverified | Latency/query |",
             "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    lines += [row(n, r) for n, r in runs]
    lines += ["", "**Reading the groundedness columns.** *Grounded first try* counts verdicts whose every cited edge existed. "
              "*Repaired by retry* were caught citing a non-existent edge and fixed by constrained regeneration. "
              "*Flagged unverified* still failed after two retries and were shown with a 20% risk penalty and an "
              "[unverified] tag instead of false confidence. The template row is grounded by construction.", ""]
    for n, r in runs:
        if r.get("llm_enrichment"):
            lines += [f"LLM extraction ({n}): {json.dumps(r['llm_enrichment'])}", ""]
    out = ROOT / "evaluation" / "results" / "model_comparison.md"
    out.write_text("\n".join(lines))
    print("\n".join(lines))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
